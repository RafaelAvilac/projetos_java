
package com.poo.prj_calculadoraeqseggrau_pooi.models;

public class DadosSaida {
    
    private double delta;
    private double x1L;
    private double x2L;
    private double xV;
    private double yV;

    public double getDelta() {
        return delta;
    }

    public void setDelta(double delta) {
        this.delta = delta;
    }

    public double getX1L() {
        return x1L;
    }

    public void setX1L(double x1L) {
        this.x1L = x1L;
    }

    public double getX2L() {
        return x2L;
    }

    public void setX2L(double x2L) {
        this.x2L = x2L;
    }

    public double getxV() {
        return xV;
    }

    public void setxV(double xV) {
        this.xV = xV;
    }

    public double getyV() {
        return yV;
    }

    public void setyV(double yV) {
        this.yV = yV;
    }
    
    
}
